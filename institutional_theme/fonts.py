"""Fonts: upload validation, the uploaded-font stylesheet and the Print Style font block (ADR 0004).

Pure functions on strings and bytes. This module never imports Frappe, so it is unit-tested without
a site; the Settings doctype, `site_files.ensure()` and `print/ship.py` call it with the data they read.

Family names are private (`Midad ...`), because another app on the owner's bench registers
"IBM Plex Sans Arabic". The bundled faces are declared in `public/scss/fonts/`; the names here must
match them (a unit test compares the two).
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path

PAIRINGS: tuple[str, ...] = ("IBM Plex", "Noto", "Tajawal", "Uploaded")
DEFAULT_PAIRING = "IBM Plex"

# Bundle linked for a pairing. IBM Plex is inside ins_desk and ins_web; Uploaded has a per-site file.
PAIRING_BUNDLES: dict[str, str | None] = {
	"IBM Plex": None,
	"Noto": "ins_fonts_noto.bundle.css",
	"Tajawal": "ins_fonts_tajawal.bundle.css",
	"Uploaded": None,
}

ASSET_BASE = "/assets/institutional_theme/fonts"

ARABIC_RANGE = "U+0600-06FF, U+0750-077F, U+08A0-08FF, U+FB50-FDFF, U+FE70-FEFF, U+200C-200F"

FAMILY_PLEX_ARABIC = "Midad Plex Sans Arabic"
FAMILY_PLEX_LATIN = "Midad Plex Sans"
FAMILY_PLEX_MONO = "Midad Plex Mono"
FAMILY_UPLOADED_ARABIC = "Midad Uploaded Arabic"
FAMILY_UPLOADED_LATIN = "Midad Uploaded Latin"

SYSTEM_TAIL = "system-ui, sans-serif"

# Magic numbers of the accepted formats: WOFF2, TrueType (00 01 00 00) and Apple TrueType ("true").
_MAGIC: tuple[tuple[bytes, str], ...] = (
	(b"wOF2", "woff2"),
	(b"\x00\x01\x00\x00", "ttf"),
	(b"true", "ttf"),
)
_FORMATS = {"woff2": "woff2", "ttf": "truetype"}

# An uploaded file is referenced by a root-relative URL with no character that could end the url() token.
_SAFE_URL = re.compile(r"^/[A-Za-z0-9._~%/@+=,-]+$")

UPLOAD_KEYS: tuple[str, ...] = ("arabic_regular", "arabic_semibold", "latin_regular", "latin_semibold")

HEADER = "/* generated by institutional_theme.fonts from the Institutional Theme Settings; do not edit */\n"


# ----------------------------------------------------------------------------------------------
# Upload validation
# ----------------------------------------------------------------------------------------------


def font_kind(head: bytes) -> str | None:
	"""`"woff2"` or `"ttf"` from the first four bytes of a file; `None` for anything else."""
	for magic, kind in _MAGIC:
		if head[:4] == magic:
			return kind
	return None


def file_kind(path: str | Path) -> str | None:
	"""`font_kind` of a file on disk. Reads four bytes; `None` for a missing or unreadable file."""
	try:
		with open(path, "rb") as handle:
			return font_kind(handle.read(4))
	except OSError:
		return None


@dataclass(frozen=True)
class UploadedFont:
	"""One uploaded file: its public URL (percent-encoded by the caller) and its kind."""

	url: str
	kind: str

	def __post_init__(self) -> None:
		if self.kind not in _FORMATS:
			raise ValueError(f"Unknown font kind: {self.kind}")
		if not _SAFE_URL.match(self.url):
			raise ValueError(f"Unsafe font URL: {self.url!r}")


def usable_scripts(fonts: Mapping[str, UploadedFont | None]) -> tuple[str, ...]:
	"""Scripts (`arabic`, `latin`) with both a regular and a semibold file. Others fall back to Plex."""
	return tuple(
		script for script in ("arabic", "latin") if fonts.get(f"{script}_regular") and fonts.get(f"{script}_semibold")
	)


# ----------------------------------------------------------------------------------------------
# Uploaded-font stylesheet
# ----------------------------------------------------------------------------------------------


def _face(family: str, weight: str, font: UploadedFont, *, arabic: bool, with_format: bool = True) -> str:
	lines = [
		"@font-face {",
		f'\tfont-family: "{family}";',
		"\tfont-style: normal;",
		f"\tfont-weight: {weight};",
		"\tfont-display: swap;",
	]
	source = f'url("{font.url}")'
	if with_format:
		source += f' format("{_FORMATS[font.kind]}")'
	lines.append(f"\tsrc: {source};")
	if arabic:
		lines.append(f"\tunicode-range: {ARABIC_RANGE};")
	lines.append("}")
	return "\n".join(lines) + "\n"


def uploaded_font_css(fonts: Mapping[str, UploadedFont | None]) -> str:
	"""Stylesheet of the uploaded pairing, or `""` when no script has both of its files.

	`fonts` has the keys `arabic_regular`, `arabic_semibold`, `latin_regular`, `latin_semibold`; a
	missing file is `None`. A script lacking either file loses both of its faces and keeps Plex.
	Regular is `font-weight: 400` and semibold covers `500 600`, so 500, 600 and 700 never fall back to
	synthesised bold; the medium and strong weight variables are 600. The variables sit on
	`html:root[dir][lang]` (0,3,1), so they win whatever the load order.
	"""
	scripts = usable_scripts(fonts)
	if not scripts:
		return ""
	parts = [HEADER]
	stack: list[str] = []
	arabic_stack: list[str] = []
	for script in ("arabic", "latin"):
		if script not in scripts:
			continue
		family = FAMILY_UPLOADED_ARABIC if script == "arabic" else FAMILY_UPLOADED_LATIN
		is_arabic = script == "arabic"
		regular, semibold = fonts[f"{script}_regular"], fonts[f"{script}_semibold"]
		parts.append(_face(family, "400", regular, arabic=is_arabic))  # type: ignore[arg-type]
		parts.append(_face(family, "500 600", semibold, arabic=is_arabic))  # type: ignore[arg-type]
		stack.append(f'"{family}"')
		if is_arabic:
			arabic_stack.append(f'"{family}"')
	stack += [f'"{FAMILY_PLEX_ARABIC}"', f'"{FAMILY_PLEX_LATIN}"', SYSTEM_TAIL]
	arabic_stack += [f'"{FAMILY_PLEX_ARABIC}"', SYSTEM_TAIL]
	parts.append(
		"html:root[dir][lang] {\n"
		f"\t--ins-font-sans: {', '.join(stack)};\n"
		f"\t--ins-font-arabic: {', '.join(arabic_stack)};\n"
		"\t--ins-weight-medium: 600;\n"
		"\t--ins-weight-strong: 600;\n"
		"\t--weight-medium: 600;\n"
		"\t--weight-semibold: 600;\n"
		"\t--weight-bold: 600;\n"
		"}\n"
	)
	return "\n".join(parts)


