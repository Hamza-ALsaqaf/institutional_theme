# Bundled TTF faces for wkhtmltopdf, which has no WOFF2 (findings section 6): (family, weight, file).
# Only IBM Plex ships TTF; the Noto and Tajawal pairings print in Plex.
PLEX_PRINT_FACES: dict[str, tuple[tuple[str, str, str], ...]] = {
	"arabic": (
		(FAMILY_PLEX_ARABIC, "400", "IBMPlexSansArabic-Regular.ttf"),
		(FAMILY_PLEX_ARABIC, "500", "IBMPlexSansArabic-Medium.ttf"),
		(FAMILY_PLEX_ARABIC, "600", "IBMPlexSansArabic-SemiBold.ttf"),
	),
	"latin": (
		(FAMILY_PLEX_LATIN, "400", "IBMPlexSans-Regular.ttf"),
		(FAMILY_PLEX_LATIN, "500", "IBMPlexSans-Medium.ttf"),
		(FAMILY_PLEX_LATIN, "600", "IBMPlexSans-SemiBold.ttf"),
	),
	"mono": (
		(FAMILY_PLEX_MONO, "400", "IBMPlexMono-Regular.ttf"),
		(FAMILY_PLEX_MONO, "500", "IBMPlexMono-Medium.ttf"),
	),
}


def _print_sources(
	pairing: str, uploaded: Mapping[str, UploadedFont | None] | None
) -> dict[str, list[tuple[str, str, str, bool]]]:
	"""Per script, the faces to declare as `(family, weight, url, is_arabic)`, in order."""
	if pairing not in PAIRINGS:
		raise ValueError(f"Unknown font pairing: {pairing}")
	own = usable_scripts(uploaded) if pairing == "Uploaded" and uploaded else ()
	sources: dict[str, list[tuple[str, str, str, bool]]] = {}
	for script in ("arabic", "latin"):
		fonts = uploaded or {}
		regular, semibold = fonts.get(f"{script}_regular"), fonts.get(f"{script}_semibold")
		if script in own and regular and semibold and regular.kind == "ttf" and semibold.kind == "ttf":
			family = FAMILY_UPLOADED_ARABIC if script == "arabic" else FAMILY_UPLOADED_LATIN
			sources[script] = [
				(family, "400", regular.url, script == "arabic"),
				(family, "500 600", semibold.url, script == "arabic"),
			]
		else:
			sources[script] = [
				(family, weight, f"{ASSET_BASE}/plex/{name}", script == "arabic")
				for family, weight, name in PLEX_PRINT_FACES[script]
			]
	sources["mono"] = [
		(family, weight, f"{ASSET_BASE}/plex/{name}", False) for family, weight, name in PLEX_PRINT_FACES["mono"]
	]
	return sources


def print_font_css(pairing: str, uploaded: Mapping[str, UploadedFont | None] | None = None) -> str:
	"""`@font-face` rules for the Print Style: one TTF `url()` per face and no `format()`.

	wkhtmltopdf reads neither WOFF2 nor the screen stylesheets, and core's `scrub_urls` rewrites
	`: url(` and appends `!important`, which breaks a multi-source `src` (findings section 6). Uploaded
	TTF files are used for a script when both of its files are TTF; otherwise, and for every bundled
	pairing, the bundled Plex TTF files are used.
	"""
	parts = [HEADER]
	for script, faces in _print_sources(pairing, uploaded).items():
		for family, weight, url, is_arabic in faces:
			font = UploadedFont(url, "ttf")
			parts.append(_face(family, weight, font, arabic=is_arabic, with_format=False))
	return "\n".join(parts)


def print_font_families(pairing: str, uploaded: Mapping[str, UploadedFont | None] | None = None) -> dict[str, str]:
	"""CSS `font-family` values for the print body (`sans`) and for code (`mono`)."""
	sources = _print_sources(pairing, uploaded)
	families: list[str] = []
	for script in ("arabic", "latin"):
		family = sources[script][0][0]
		if family not in families:
			families.append(family)
	for family in (FAMILY_PLEX_ARABIC, FAMILY_PLEX_LATIN):
		if family not in families:
			families.append(family)
	return {
		"sans": ", ".join([*(f'"{f}"' for f in families), "sans-serif"]),
		"mono": f'"{FAMILY_PLEX_MONO}", monospace',
	}
