"""Readers of the watched custom properties that live outside the compiled stylesheets.

The dead-token snapshot (`dead_tokens.py`) reads each version's compiled CSS. Core also reads variables
elsewhere: an inline `<style>` in a form (`error_log.js`), a page stylesheet that is not part of a bundle
(`desktop.css`), JavaScript that builds `var(--name)` or names a property, a Vue component, and the libraries
that style themselves (frappe-gantt, FullCalendar). Those readers decide whether an override has an effect, so
each supported version has a committed snapshot of them (`data/source_readers_frappe_<version>.json`), written
from a source tree by this module:

    python -m institutional_theme.audits.source_readers --version 16.32.0 --write \\
        --tree frappe=/path/frappe-v16.32.0 --exclude frappe=ui \\
        --tree erpnext=/path/erpnext --exclude erpnext=banking \\
        --tree gantt=/path/frappe-gantt/src

`--tree LABEL=DIR` adds a directory (or one file) to scan, `--exclude LABEL=PREFIX` skips a path prefix of that
tree. `node_modules`, `dist` and translation folders are always skipped inside a tree (give a library's own folder
as a tree to include it). Only the names the theme watches are recorded, with up to four `label/path:line`
locations each. A read is `var(--name`, or the name in quotes (`"--name"`, `'--name'`, a template literal), which
is how JavaScript hands a name to `getPropertyValue` or builds `var(${name})`. Comments do not count.

Never imports Frappe.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from institutional_theme.midad import model as model_mod

from . import dead_tokens

_READ_OR_NAMED = re.compile(r"var\(\s*(--[A-Za-z0-9_-]+)|[\"'`](--[A-Za-z0-9_-]+)[\"'`]")
SUFFIXES = frozenset({".scss", ".css", ".js", ".mjs", ".vue", ".ts", ".html", ".py"})
SKIPPED_DIRS = frozenset({"node_modules", "dist", ".git", "__pycache__", "locale", "translations"})
LOCATIONS_PER_NAME = 4
GENERATED = "generated by python -m institutional_theme.audits.source_readers --write; do not edit"


def snapshot_path(version: str) -> Path:
	return dead_tokens.DATA_DIR / f"source_readers_frappe_{version}.json"


def _files(root: Path, excluded: tuple[str, ...]):
	if root.is_file():
		yield root, root.name
		return
	for path in sorted(root.rglob("*")):
		if not path.is_file() or path.suffix not in SUFFIXES:
			continue
		relative = path.relative_to(root)
		if SKIPPED_DIRS.intersection(relative.parts[:-1]):
			continue
		posix = relative.as_posix()
		if any(posix == prefix or posix.startswith(prefix.rstrip("/") + "/") for prefix in excluded):
			continue
		yield path, posix


def readers_in_text(text: str, suffix: str) -> list[tuple[str, int]]:
	"""`(name, line)` for every read in `text`; comments (CSS, SCSS, JavaScript) are removed first.

	HTML and Vue templates keep their `<!-- -->` text out as well. Line numbers are those of the original
	text, because stripping keeps the newlines of a block comment.
	"""
	if suffix in (".html", ".vue"):
		text = re.sub(r"<!--.*?-->", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.DOTALL)
	if suffix != ".html":
		text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.DOTALL)
		if suffix != ".css":
			text = dead_tokens._TRAILING_COMMENT.sub("", dead_tokens._LINE_COMMENT.sub("", text))
	found = []
	for number, line in enumerate(text.splitlines(), start=1):
		for var_name, quoted in _READ_OR_NAMED.findall(line):
			found.append((var_name or quoted, number))
	return found


def scan(
	trees: dict[str, Path], names: set[str] | None, excluded: dict[str, tuple[str, ...]] | None = None
) -> dict[str, list[str]]:
	"""`{name: [label/path:line, ...]}` for the `names` read anywhere in the trees (every name when `None`)."""
	excluded = excluded or {}
	found: dict[str, list[str]] = {}
	for label, root in trees.items():
		for path, relative in _files(root, excluded.get(label, ())):
			text = path.read_text(encoding="utf-8", errors="replace")
			for name, number in readers_in_text(text, path.suffix):
				if names is None or name in names:
					where = f"{label}/{relative}:{number}"
					locations = found.setdefault(name, [])
					if where not in locations:
						locations.append(where)
	return {name: found[name][:LOCATIONS_PER_NAME] for name in sorted(found)}


def write_snapshot(
	path: Path,
	version: str,
	readers: dict[str, list[str]],
	trees: dict[str, str],
	excluded: dict[str, tuple[str, ...]],
	watched: int,
) -> None:
	data = {
		"_generated": GENERATED,
		"version": version,
		"trees": trees,
		"excluded": {label: list(prefixes) for label, prefixes in sorted(excluded.items())},
		"watched_names_scanned_for": watched,
		"readers": readers,
	}
	path.parent.mkdir(parents=True, exist_ok=True)
	path.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def load_snapshot(version: str, data_dir: Path | None = None) -> dict[str, list[str]]:
	"""The committed readers of one version; an empty dict when the version has no snapshot."""
	path = snapshot_path(version) if data_dir is None else data_dir / snapshot_path(version).name
	if not path.is_file():
		return {}
	return json.loads(path.read_text(encoding="utf-8"))["readers"]


def main(argv: list[str] | None = None) -> int:
	parser = argparse.ArgumentParser(
		prog="python -m institutional_theme.audits.source_readers", description=__doc__
	)
	parser.add_argument("--version", required=True, help="Frappe version the trees belong to")
	parser.add_argument("--tree", action="append", default=[], metavar="LABEL=DIR", required=True)
	parser.add_argument("--exclude", action="append", default=[], metavar="LABEL=PREFIX")
	parser.add_argument(
		"--write", action="store_true", help="write data/source_readers_frappe_<version>.json"
	)
	args = parser.parse_args(argv)

	trees: dict[str, Path] = {}
	for spec in args.tree:
		label, _, raw = spec.partition("=")
		if not raw or not Path(raw).exists():
			parser.error(f"--tree {spec}: path not found")
		trees[label] = Path(raw)
	excluded: dict[str, list[str]] = {}
	for spec in args.exclude:
		label, _, prefix = spec.partition("=")
		if label not in trees:
			parser.error(f"--exclude {spec}: no tree {label}")
		excluded.setdefault(label, []).append(prefix)

	model = model_mod.load_model()
	theme_root = Path(__file__).resolve().parents[1] / "public"
	names = set(dead_tokens.watched_variables(model, theme_root))
	readers = scan(trees, names, {label: tuple(prefixes) for label, prefixes in excluded.items()})
	print(f"Frappe {args.version}: {len(readers)} of {len(names)} watched names are read in the source trees")
	if args.write:
		target = snapshot_path(args.version)
		write_snapshot(
			target,
			args.version,
			readers,
			{label: path.name for label, path in trees.items()},
			{label: tuple(prefixes) for label, prefixes in excluded.items()},
			len(names),
		)
		print(f"wrote {target}")
	return 0


if __name__ == "__main__":
	sys.exit(main())
