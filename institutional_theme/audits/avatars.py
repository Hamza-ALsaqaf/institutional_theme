"""Avatar contrast audit: the nine desk avatar colour pairs, both modes, every preset.

Core renders a user's initials inline as `background-color: var(--<colour>-avatar-bg); color:
var(--<colour>-avatar-color)` (`frappe/public/scss/desk/avatar.scss`), and chooses the colour from the
user's name, so any of the nine pairs can appear. The theme remaps each pair to a status pair in
`public/scss/desk/_avatar.scss` (and, for the website, `public/scss/web/_website.scss`). This audit
reads those two files, resolves each `var(--ins-<token>)` through the model in Light and Dark for every
preset, and requires 4.5:1 (the initials are 12 to 14 px). It also requires both files to define the
same nine pairs with the same tokens, and each token to exist. The `--ins-` values switch with the mode,
so one declaration serves Light and Dark. Never imports Frappe.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path

from institutional_theme.midad import colour
from institutional_theme.midad import model as model_mod
from institutional_theme.midad.model import MODES, Model, Palette

COLOURS = ("orange", "pink", "blue", "green", "dark-green", "red", "yellow", "purple", "gray")
MINIMUM = 4.5
SOURCES = ("scss/desk/_avatar.scss", "scss/web/_website.scss")

_DECLARATION = re.compile(r"--([a-z]+(?:-[a-z]+)*)-avatar-(bg|color)\s*:\s*([^;]+);")
_TOKEN = re.compile(r"^var\(--ins-([a-z0-9]+(?:-[a-z0-9]+)*)\)$")


@dataclass(frozen=True)
class AvatarResult:
	"""One measured pair."""

	preset: str
	shipped: bool
	source: str
	colour: str
	bg: str
	fg: str
	mode: str
	ratio: float
	passed: bool


@dataclass
class AvatarAudit:
	"""Results plus the structural problems found while reading the files."""

	results: list[AvatarResult] = field(default_factory=list)
	problems: list[str] = field(default_factory=list)

	@property
	def failures(self) -> list[AvatarResult]:
		return [r for r in self.results if r.shipped and not r.passed]

	@property
	def fatal(self) -> int:
		return len(self.failures) + len(self.problems)


def read_pairs(text: str) -> dict[str, dict[str, str]]:
	"""`{colour: {"bg": value, "color": value}}` from the avatar declarations of a stylesheet."""
	pairs: dict[str, dict[str, str]] = {}
	for name, part, value in _DECLARATION.findall(text):
		pairs.setdefault(name, {})[part] = value.strip()
	return pairs


def _token(value: str) -> str | None:
	found = _TOKEN.match(value)
	return found.group(1) if found else None


def run(model: Model, palettes: dict[str, Palette], public: Path) -> AvatarAudit:
	"""Measure the pairs of every source file for every preset, and check the files agree."""
	audit = AvatarAudit()
	shipped = set(model["palettes"]["shipped"])
	read: dict[str, dict[str, dict[str, str]]] = {}
	for source in SOURCES:
		path = public / source
		if not path.is_file():
			audit.problems.append(f"{source}: file not found")
			continue
		pairs = read[source] = read_pairs(path.read_text(encoding="utf-8"))
		for name in COLOURS:
			missing = [p for p in ("bg", "color") if p not in pairs.get(name, {})]
			if missing:
				audit.problems.append(f"{source}: --{name}-avatar-{' and -'.join(missing)} not declared")
		for name in sorted(set(pairs) - set(COLOURS)):
			audit.problems.append(f"{source}: --{name}-avatar-* is not one of the nine core colours")
		for name in COLOURS:
			for part in ("bg", "color"):
				value = pairs.get(name, {}).get(part)
				if value is not None and (_token(value) is None or _token(value) not in model["semantic"]):
					audit.problems.append(
						f"{source}: --{name}-avatar-{part} is {value}, not a var() of a theme token"
					)
	if len(read) == 2:
		desk, web = (read[s] for s in SOURCES)
		for name in COLOURS:
			if desk.get(name) != web.get(name):
				audit.problems.append(
					f"the desk and website pairs differ for {name}: {desk.get(name)} and {web.get(name)}"
				)
	for source, pairs in read.items():
		for name in COLOURS:
			bg = _token(pairs.get(name, {}).get("bg", ""))
			fg = _token(pairs.get(name, {}).get("color", ""))
			if bg is None or fg is None or bg not in model["semantic"] or fg not in model["semantic"]:
				continue
			for preset, palette in palettes.items():
				for mode in MODES:
					ratio = colour.contrast(palette.colour(fg, mode), palette.colour(bg, mode))
					audit.results.append(
						AvatarResult(
							preset, preset in shipped, source, name, bg, fg, mode, ratio, ratio >= MINIMUM
						)
					)
	return audit


def render_text(audit: AvatarAudit, palettes: dict[str, Palette]) -> str:
	"""One row per colour, preset and mode of the desk file, then every problem."""
	lines = [
		"Avatar contrast audit",
		"Generated by python -m institutional_theme.audits; do not edit.",
		"",
		f"The nine desk avatar pairs (`--<colour>-avatar-bg` and `-color`), remapped in {SOURCES[0]} and {SOURCES[1]}.",
		f"Each pair must reach {MINIMUM}:1 in Light and Dark for every shipped preset (12 to 14 px initials).",
		"",
	]
	desk = [r for r in audit.results if r.source == SOURCES[0]]
	for preset, palette in palettes.items():
		rows = [r for r in desk if r.preset == preset]
		if not rows:
			continue
		lines.append(f"== {preset} ({'shipped' if rows[0].shipped else 'NOT SHIPPED'})")
		for mode in MODES:
			lines.append(f"-- {mode}")
			for name in COLOURS:
				for r in (x for x in rows if x.mode == mode and x.colour == name):
					lines.append(
						f"  {'ok  ' if r.passed else 'FAIL'} {r.ratio:6.2f}:1  {name:10} "
						f"{palette.colour(r.fg, mode)} on {palette.colour(r.bg, mode)}  [{r.fg} on {r.bg}]"
					)
		lines.append("")
	for problem in audit.problems:
		lines.append(f"Problem: {problem}")
	lines.append(f"Failing pairs in shipped presets: {len(audit.failures)}; problems: {len(audit.problems)}")
	return "\n".join(lines) + "\n"


def run_default(public: Path) -> tuple[AvatarAudit, dict[str, Palette]]:
	"""The audit for the committed model; used by the runner."""
	model = model_mod.load_model()
	palettes = {name: model_mod.palette(model, name) for name in model["palettes"]["presets"]}
	return run(model, palettes, public), palettes
