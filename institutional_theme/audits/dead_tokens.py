"""Dead-token audit: every Frappe variable this theme overrides must exist in core.

A variable passes when Frappe's compiled CSS declares it (`--name:`) or reads it (`var(--name)`),
or when this theme's own stylesheets consume it (`var(--name)` outside the generated folder).
A variable found nowhere is dead: the override would do nothing and signals a typo or a variable
that a Frappe upgrade removed.

Runs only when `--core-css PATH` is given, where PATH is a compiled core stylesheet or a folder
of them (for example `apps/frappe/frappe/public/dist/css`). Never imports Frappe.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from institutional_theme.midad import model as model_mod
from institutional_theme.midad.model import Model

_DECLARED = re.compile(r"(--[A-Za-z0-9_-]+)\s*:")
_READ = re.compile(r"var\(\s*(--[A-Za-z0-9_-]+)")


@dataclass(frozen=True)
class Result:
	"""Where a variable was found: `declared`, `read`, `theme` or `dead`."""

	name: str
	where: str


def core_stylesheets(paths: list[Path]) -> list[Path]:
	"""Expand files and folders (non-recursive, `*.css` only) into stylesheet paths."""
	found: list[Path] = []
	for path in paths:
		if path.is_dir():
			found += sorted(path.glob("*.css"))
		elif path.is_file():
			found.append(path)
		else:
			raise FileNotFoundError(f"--core-css path not found: {path}")
	if not found:
		raise FileNotFoundError("--core-css matched no stylesheet")
	return found


def scan_core(paths: list[Path]) -> tuple[set[str], set[str]]:
	"""Custom properties declared and read by the given stylesheets."""
	declared: set[str] = set()
	read: set[str] = set()
	for path in core_stylesheets(paths):
		text = path.read_text(encoding="utf-8", errors="replace")
		declared.update(_DECLARED.findall(text))
		read.update(_READ.findall(text))
	return declared, read


def scan_theme(scss_root: Path) -> set[str]:
	"""Custom properties this theme reads outside its generated folder (SCSS and JS sources)."""
	used: set[str] = set()
	for pattern in ("**/*.scss", "**/*.css", "**/*.js"):
		for path in scss_root.glob(pattern):
			if "generated" in path.parts or "node_modules" in path.parts:
				continue
			used.update(_READ.findall(path.read_text(encoding="utf-8", errors="replace")))
	return used


def overridden_variables(model: Model) -> list[str]:
	"""Every Frappe variable the theme sets, in map order, without duplicates."""
	names = [name for name, _ in model_mod.frappe_map(model).declarations["light"]]
	return list(dict.fromkeys(names))


def audit(model: Model, core_paths: list[Path], theme_root: Path) -> list[Result]:
	declared, read = scan_core(core_paths)
	theme = scan_theme(theme_root)
	results = []
	for name in overridden_variables(model):
		if name in declared:
			where = "declared"
		elif name in read:
			where = "read"
		elif name in theme:
			where = "theme"
		else:
			where = "dead"
		results.append(Result(name, where))
	return results


def render_text(results: list[Result], core_paths: list[Path]) -> str:
	dead = [r for r in results if r.where == "dead"]
	counts = {
		kind: sum(1 for r in results if r.where == kind) for kind in ("declared", "read", "theme", "dead")
	}
	lines = [
		"Dead-token audit",
		"Generated by python -m institutional_theme.audits; do not edit.",
		"",
		"Core stylesheets scanned: " + ", ".join(p.name for p in core_stylesheets(core_paths)),
		f"Variables overridden by the theme: {len(results)}",
		f"  declared by core: {counts['declared']}",
		f"  only read by core (never declared): {counts['read']}",
		f"  consumed by this theme only: {counts['theme']}",
		f"  dead (found nowhere): {counts['dead']}",
		"",
	]
	if counts["read"]:
		lines.append("Read by core but never declared (the override defines them; verify the intent):")
		lines += [f"  {r.name}" for r in results if r.where == "read"]
		lines.append("")
	if counts["theme"]:
		lines.append("Not in core, consumed by this theme:")
		lines += [f"  {r.name}" for r in results if r.where == "theme"]
		lines.append("")
	if dead:
		lines.append("DEAD:")
		lines += [f"  {r.name}" for r in dead]
	else:
		lines.append("No dead variables.")
	return "\n".join(lines) + "\n"
