"""Contrast audit: every pair of `contrast.groups` and `contrast.max`, both modes, every preset.

`min` pairs must reach their ratio (a miss is a failure); the `target` is advisory and only
counted. `max` pairs (gridlines) must not exceed their ratio. Never imports Frappe.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any

from institutional_theme.midad import model as model_mod
from institutional_theme.midad.model import MODES, Model, PairResult, Palette


@dataclass
class PresetContrast:
	"""Contrast results of one preset."""

	name: str
	shipped: bool
	palette: Palette
	results: list[PairResult]

	@property
	def failures(self) -> list[PairResult]:
		return [r for r in self.results if not r.passed]

	@property
	def below_target(self) -> list[PairResult]:
		return [r for r in self.results if r.passed and r.kind == "min" and r.target and r.ratio < r.target]


def run(model: Model, palettes: dict[str, Palette]) -> list[PresetContrast]:
	"""Measure every preset of the model (shipped or not)."""
	shipped = set(model["palettes"]["shipped"])
	return [
		PresetContrast(name, name in shipped, built, model_mod.contrast_results(model, built))
		for name, built in palettes.items()
	]


def fatal_count(presets: list[PresetContrast]) -> int:
	"""Failing pairs in shipped presets (a dropped preset never counts)."""
	return sum(len(p.failures) for p in presets if p.shipped)


def _limit(result: PairResult) -> str:
	return f"<= {result.limit}" if result.kind == "max" else f">= {result.limit}"


def render_text(model: Model, presets: list[PresetContrast]) -> str:
	"""Group-by-group summary per preset and mode, then every failing pair."""
	lines = [
		"Contrast audit",
		"Generated by python -m institutional_theme.audits; do not edit.",
		"",
		"WCAG 2.x contrast ratio on opaque sRGB hex. Every pair of contrast.groups and contrast.max,",
		"Light and Dark. A pair below its minimum fails; below its target only counts as advisory.",
		"The row shows the closest pair of the group (lowest ratio; highest for max rules).",
		"",
	]
	for preset in presets:
		lines.append(f"== {preset.name} ({'shipped' if preset.shipped else 'NOT SHIPPED'})")
		for mode in MODES:
			mode_results = [r for r in preset.results if r.mode == mode]
			failed = [r for r in mode_results if not r.passed]
			lines.append(
				f"-- {mode}: {len(mode_results)} pairs, {len(failed)} failing, "
				f"{len([r for r in preset.below_target if r.mode == mode])} below target"
			)
			groups: dict[str, list[PairResult]] = {}
			for result in mode_results:
				groups.setdefault(result.group, []).append(result)
			for group, items in groups.items():
				pick = (
					max(items, key=lambda r: r.ratio)
					if items[0].kind == "max"
					else min(items, key=lambda r: r.ratio)
				)
				status = "ok  " if all(r.passed for r in items) else "FAIL"
				note = ""
				if status == "ok  " and pick.target and any(r.ratio < r.target for r in items if r.target):
					note = " below target"
				lines.append(
					f"  {status} {pick.ratio:6.2f}:1 {_limit(pick):>8}  {group} "
					f"[{len(items)} pairs; closest {pick.fg} on {pick.bg}]{note}"
				)
		failures = model_mod.describe_failures(model, preset.results)
		if failures:
			lines.append("Failing pairs:")
			for item in failures:
				lines.append(
					f"  {item['fg']} on {item['bg']}, {item['mode']}: {item['ratio_text']}:1, "
					f"required {item['required']}:1, adjust the {item['adjust'] or 'unknown'} colour"
				)
		lines.append("")
	lines.append(f"Failing pairs in shipped presets: {fatal_count(presets)}")
	return "\n".join(lines) + "\n"


def _dump(value: Any, depth: int = 0, inline_from: int = 5) -> str:
	"""JSON with tab indentation; containers at `inline_from` depth or deeper stay on one line."""
	scalar_list = isinstance(value, list) and not any(isinstance(v, dict | list) for v in value)
	if isinstance(value, dict | list) and depth < inline_from and not scalar_list:
		pad = "\t" * (depth + 1)
		if isinstance(value, dict):
			rows = [f"{pad}{json.dumps(k)}: {_dump(v, depth + 1, inline_from)}" for k, v in value.items()]
			open_, close = "{", "}"
		else:
			rows = [f"{pad}{_dump(v, depth + 1, inline_from)}" for v in value]
			open_, close = "[", "]"
		if not rows:
			return open_ + close
		return open_ + "\n" + ",\n".join(rows) + "\n" + "\t" * depth + close
	return json.dumps(value, ensure_ascii=False)


def render_json(model: Model, presets: list[PresetContrast]) -> str:
	"""Machine-readable results for the proof panel: one line per pair, hex included."""
	data: dict[str, Any] = {
		"_generated": "generated by python -m institutional_theme.audits; do not edit",
		"default": model["palettes"]["default"],
		"shipped": model["palettes"]["shipped"],
		"presets": {},
	}
	for preset in presets:
		modes: dict[str, list[dict[str, Any]]] = {}
		for mode in MODES:
			modes[mode] = [
				{
					"group": result.group,
					"fg": result.fg,
					"bg": result.bg,
					"fg_hex": preset.palette.colour(result.fg, mode),
					"bg_hex": preset.palette.colour(result.bg, mode),
					"ratio": round(result.ratio, 3),
					result.kind: result.limit,
					"target": result.target,
					"pass": result.passed,
				}
				for result in preset.results
				if result.mode == mode
			]
		data["presets"][preset.name] = {
			"shipped": preset.shipped,
			"failures": len(preset.failures),
			"modes": modes,
		}
	return _dump(data, inline_from=5) + "\n"
