"""Which mapped Frappe variables the website pages read, and the proof that the desk-only ones are not among them.

The website bundle (`ins_web.bundle.scss`) imports a light-only map. A variable that only desk components
read has no use there, so `design/tokens.json` marks it `"scope": "desk"` and the website variant of the map
leaves it out (the bundle stays under its size budget). This module is the proof that the mark is safe:

* `data/web_reads_frappe_<version>.json` records, for each supported version, every custom property that the
  website pages can read: the compiled stylesheets they load (`website`, `login`, `web_form` and the ERPNext web
  bundle), the scripts they load (`frappe-web`, `web_form`, `controls`, `dialog`) and the source of the website
  templates and pages (`templates`, `www`, `website` of Frappe and ERPNext, `www` and `templates` of HRMS). A name
  is read when it is in `var(--name`, or in quotes (JavaScript passing a property name). Comments do not count.
* `check` fails for every variable marked `scope: desk` that a supported version's website pages read, or that
  this theme's own website stylesheets read. A read by a stylesheet that is loaded is enough: the audit does not
  try to prove that no element matches the rule, because a page with an editor, a menu or a popover may.
* `candidates` lists the unmarked variables of the map that no website page reads, so the list stays complete
  (reported, not fatal: an unmarked name only costs bytes).

Write the snapshots from a built bench and the source trees:

    python -m institutional_theme.audits.web_scope --version 16.32.0 --write \\
        --assets /path/bench/sites/assets --tree frappe=/path/frappe/frappe/templates ...

(`tools/bench/write_source_readers.sh` runs it for both versions.) Never imports Frappe.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

from institutional_theme.midad import model as model_mod
from institutional_theme.midad.model import Model

from . import dead_tokens, source_readers

FRAPPE_STYLES = ("website.bundle", "login.bundle", "web_form.bundle")
ERPNEXT_STYLES = ("erpnext-web.bundle",)
FRAPPE_SCRIPTS = ("frappe-web.bundle", "web_form.bundle", "controls.bundle", "dialog.bundle")
GENERATED = "generated by python -m institutional_theme.audits.web_scope --write; do not edit"
# The theme's own website sources: the bundle, its partials and the script.
THEME_WEB = ("scss/ins_web.bundle.scss", "scss/web", "scss/fonts", "js/ins_web.bundle.js")


def snapshot_path(version: str) -> Path:
	return dead_tokens.DATA_DIR / f"web_reads_frappe_{version}.json"


def _bundle(directory: Path, stem: str, suffix: str) -> Path | None:
	"""The built file of a bundle (`website.bundle.ABC123.css`), the newest when several exist."""
	found = sorted(directory.glob(f"{stem}.*{suffix}"), key=lambda path: path.stat().st_mtime, reverse=True)
	found = [
		path
		for path in found
		if re.fullmatch(re.escape(stem) + r"\.[A-Z0-9]+" + re.escape(suffix), path.name)
	]
	return found[0] if found else None


def compiled_files(assets: Path) -> list[tuple[str, Path]]:
	"""`(label, path)` of the stylesheets and scripts the website pages load, from a bench's `sites/assets`."""
	wanted = [("frappe/dist/css", stem, ".css") for stem in FRAPPE_STYLES] + [
		("erpnext/dist/css", stem, ".css") for stem in ERPNEXT_STYLES
	]
	wanted += [("frappe/dist/js", stem, ".js") for stem in FRAPPE_SCRIPTS]
	files = []
	for folder, stem, suffix in wanted:
		path = _bundle(assets / folder, stem, suffix)
		if path is None:
			raise FileNotFoundError(f"no built {stem}{suffix} in {assets / folder}")
		files.append((f"{stem}{suffix}", path))
	return files


def scan_compiled(files: list[tuple[str, Path]]) -> tuple[dict[str, str], list[dict[str, str]]]:
	"""`({name: label of the first file that reads it}, [{file, sha256}])` over the compiled files."""
	reads: dict[str, str] = {}
	sources = []
	for label, path in files:
		raw = path.read_bytes()
		text = raw.decode("utf-8", errors="replace")
		pattern = dead_tokens._READ if label.endswith(".css") else source_readers._READ_OR_NAMED
		for match in pattern.findall(text):
			name = match if isinstance(match, str) else (match[0] or match[1])
			reads.setdefault(name, label)
		sources.append({"file": label, "sha256": hashlib.sha256(raw).hexdigest()})
	return dict(sorted(reads.items())), sources


def write_snapshot(
	path: Path, version: str, reads: dict[str, str], compiled: list[dict[str, str]], trees: dict[str, str]
) -> None:
	data = {
		"_generated": GENERATED,
		"version": version,
		"compiled": compiled,
		"trees": trees,
		"reads": dict(sorted(reads.items())),
	}
	path.parent.mkdir(parents=True, exist_ok=True)
	path.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")


def load_reads(version: str, data_dir: Path | None = None) -> dict[str, str]:
	"""`{name: where}` the website pages of a version read; an empty dict when it has no snapshot."""
	path = snapshot_path(version) if data_dir is None else data_dir / snapshot_path(version).name
	if not path.is_file():
		return {}
	return json.loads(path.read_text(encoding="utf-8"))["reads"]


def theme_reads(public_root: Path) -> dict[str, str]:
	"""`{name: file}` for the custom properties this theme's own website sources read (comments excluded)."""
	found: dict[str, str] = {}
	for entry in THEME_WEB:
		base = public_root / entry
		paths = [base] if base.is_file() else sorted(base.glob("**/*")) if base.is_dir() else []
		for path in paths:
			if not path.is_file() or path.suffix not in (".scss", ".css", ".js"):
				continue
			text = dead_tokens.strip_comments(
				path.read_text(encoding="utf-8", errors="replace"), line_comments=path.suffix != ".css"
			)
			for match in source_readers._READ_OR_NAMED.findall(text):
				found.setdefault(match[0] or match[1], path.relative_to(public_root).as_posix())
	return found


@dataclass(frozen=True)
class Scope:
	"""The outcome of the website-scope check."""

	desk_only: list[str]
	problems: list[str]
	candidates: list[str]
	versions: list[str]
	read_counts: dict[str, int]


def check(model: Model, reads: dict[str, dict[str, str]], theme: dict[str, str]) -> Scope:
	"""Fail for each `scope: desk` variable that a website page or the theme's website sources read."""
	marked = model_mod.desk_only(model)
	problems = []
	for name in marked:
		for version, found in sorted(reads.items()):
			if name in found:
				problems.append(
					f"{name}: marked scope desk but read by the website pages of Frappe {version} ({found[name]})"
				)
		if name in theme:
			problems.append(
				f"{name}: marked scope desk but read by this theme's website sources ({theme[name]})"
			)
	if not reads:
		problems.append("no committed web_reads_frappe_<version>.json: the desk scope cannot be proven")
	everything = set().union(*(set(found) for found in reads.values())) | set(theme)
	candidates = [
		name
		for name, entry in model["frappe"]["vars"].items()
		if entry.get("scope") != model_mod.SCOPE_DESK and name not in everything
	]
	return Scope(marked, problems, candidates, sorted(reads), {v: len(found) for v, found in reads.items()})


def render_text(scope: Scope, total: int) -> str:
	lines = [
		"Website scope audit",
		"Generated by python -m institutional_theme.audits; do not edit.",
		"",
		"The website bundle imports a light map without the variables marked `scope: desk` in tokens.json.",
		"Each such variable must be read by no website page of any supported version and by no website",
		"source of this theme. Reads: data/web_reads_frappe_<version>.json (the stylesheets and scripts the",
		"website pages load and the source of the website templates and pages).",
		"",
		f"Frappe variables in the map: {total}; marked scope desk and left out of the website map: {len(scope.desk_only)}",
	]
	for version in scope.versions:
		lines.append(f"Names the website pages of Frappe {version} read: {scope.read_counts[version]}")
	lines.append("")
	lines.append(
		f"Unmarked variables no website page reads ({len(scope.candidates)}; candidates for `scope: desk`):"
	)
	lines += [f"  {name}" for name in scope.candidates]
	lines.append("")
	if scope.problems:
		lines.append(f"PROBLEMS ({len(scope.problems)}):")
		lines += [f"  {problem}" for problem in scope.problems]
	else:
		lines.append("No problems: no desk-only variable is read by a website page.")
	lines.append("")
	lines.append("Marked scope desk:")
	lines += [f"  {name}" for name in scope.desk_only]
	return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
	parser = argparse.ArgumentParser(
		prog="python -m institutional_theme.audits.web_scope", description=__doc__
	)
	parser.add_argument("--version", required=True)
	parser.add_argument("--assets", required=True, help="the bench's sites/assets folder (built)")
	parser.add_argument("--tree", action="append", default=[], metavar="LABEL=DIR", required=True)
	parser.add_argument("--exclude", action="append", default=[], metavar="LABEL=PREFIX")
	parser.add_argument("--write", action="store_true")
	args = parser.parse_args(argv)

	trees: dict[str, Path] = {}
	for spec in args.tree:
		label, _, raw = spec.partition("=")
		if not raw or not Path(raw).exists():
			parser.error(f"--tree {spec}: path not found")
		trees[label] = Path(raw)
	excluded: dict[str, tuple[str, ...]] = {}
	for spec in args.exclude:
		label, _, prefix = spec.partition("=")
		excluded[label] = (*excluded.get(label, ()), prefix)

	compiled_reads, compiled = scan_compiled(compiled_files(Path(args.assets)))
	tree_reads = source_readers.scan(trees, None, excluded)
	reads = {**{name: where[0] for name, where in tree_reads.items()}, **compiled_reads}
	print(
		f"Frappe {args.version}: the website pages read {len(reads)} names "
		f"({len(compiled_reads)} compiled, {len(tree_reads)} in source)"
	)
	if args.write:
		target = snapshot_path(args.version)
		write_snapshot(
			target, args.version, reads, compiled, {label: path.name for label, path in trees.items()}
		)
		print(f"wrote {target}")
	return 0


if __name__ == "__main__":
	sys.exit(main())
