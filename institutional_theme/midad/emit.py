"""Emitter: pure text formatting for the generated stylesheets (ADR 0003).

All three blocks of a family (light, dark, automatic) are written from ONE key list, and a key
missing from either mode raises `KeyError`, so key-set parity cannot be broken silently. The
automatic block repeats the dark values inside `@media (prefers-color-scheme: dark)`. The desk Frappe map is the
one exception (`emit_map_family`): a shared block with every key, then dark and automatic blocks with only the keys
whose dark value differs.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence

HEADER_TEXT = "generated by institutional_theme.midad.build from design/tokens.json; do not edit"

RTL_BEGIN = "/*rtl:begin:ignore*/"
RTL_END = "/*rtl:end:ignore*/"

# Selector shapes of ADR 0003. Specificity in the comments is (id, class, element).
SHAPES: dict[str, dict[str, tuple[str, ...]]] = {
	# Base --ins-* tokens (midad). Light (0,1,1); dark (0,2,1) and (0,1,1); automatic (0,2,1).
	"base": {
		"light": ("html:root", 'html [data-theme="light"]'),
		"dark": ('html:root[data-theme="dark"]', 'html [data-theme="dark"]'),
		"automatic": ('html:root[data-theme="automatic"]',),
	},
	# Frappe variable mapping, every palette file and the custom file. (0,2,1) and (0,3,1).
	"palette": {
		"light": ("html:root[dir]", 'html[dir] [data-theme="light"]'),
		"dark": ('html:root[dir][data-theme="dark"]', 'html[dir] [data-theme="dark"]'),
		"automatic": ('html:root[dir][data-theme="automatic"]',),
	},
	# Frappe variable map (desk only): ONE shared block holds every declaration, the dark and automatic blocks
	# hold only the declarations whose dark value differs. The shared list is the union of the selectors of the
	# "palette" light and dark blocks: a value is a `var()` expression resolved on the element that declares it,
	# so the same expression declared once for Light and Dark changes nothing. Because the explicit Dark root
	# selector (0,3,1) is in the shared list, every mapped name keeps its old specificity on the Dark root; the
	# dark block follows at the same specificity and wins for the differing names. Not in the list: the automatic
	# selector (it would put the light values on an automatic root in a dark OS ahead of the media block) and a
	# bare `[data-theme]`. Automatic under a dark OS is the one cell where the non-differing names are declared
	# at (0,2,1) (shared root) instead of (0,3,1).
	"map": {
		"shared": (
			"html:root[dir]",
			'html[dir] [data-theme="light"]',
			'html:root[dir][data-theme="dark"]',
			'html[dir] [data-theme="dark"]',
		),
		"dark": ('html:root[dir][data-theme="dark"]', 'html[dir] [data-theme="dark"]'),
		"automatic": ('html:root[dir][data-theme="automatic"]',),
	},
}

# Scale blocks: comfortable (0,2,1), compact (0,3,1), coarse pointer (0,4,1) and (0,3,1).
SCALE_COMFORTABLE = "html:root[dir]"
SCALE_COMPACT = 'html:root[dir][data-ins-density="compact"]'
SCALE_COARSE_MEDIA = "(pointer: coarse)"
SCALE_COARSE = ("html:root[dir][data-theme-mode][data-ins-density]", "html:root[dir][data-theme-mode]")

AUTOMATIC_MEDIA = "(prefers-color-scheme: dark)"


def header(comment: str = "//") -> str:
	"""The first line of every generated file. `comment` is `//` (SCSS) or `/*` (CSS)."""
	if comment == "/*":
		return f"/* {HEADER_TEXT} */\n"
	return f"{comment} {HEADER_TEXT}\n"


def _block(selectors: Sequence[str], declarations: Sequence[tuple[str, str]], indent: str = "") -> str:
	head = (",\n" + indent).join(selectors)
	lines = [f"{indent}{head} {{"]
	lines += [f"{indent}\t{prop}: {value};" for prop, value in declarations]
	lines.append(f"{indent}}}")
	return "\n".join(lines) + "\n"


def _declarations(keys: Sequence[str], values: Mapping[str, str]) -> list[tuple[str, str]]:
	missing = [key for key in keys if key not in values]
	if missing:
		raise KeyError(f"Missing values for {len(missing)} key(s), first: {missing[0]}")
	return [(key, values[key]) for key in keys]


def emit_family(
	family: str,
	keys: Sequence[str],
	light: Mapping[str, str],
	dark: Mapping[str, str],
	*,
	color_scheme: bool = False,
) -> str:
	"""Light, dark and automatic blocks of one family from a single key list.

	`keys` are complete property names (`--ins-primary`). With `color_scheme`, the light block
	starts with `color-scheme: light`, the dark block with `color-scheme: dark`, and a separate
	`color-scheme: light dark` block follows the media query for the automatic mode.
	"""
	shape = SHAPES[family]
	light_decl = _declarations(keys, light)
	dark_decl = _declarations(keys, dark)
	if color_scheme:
		light_decl = [("color-scheme", "light"), *light_decl]
		dark_decl = [("color-scheme", "dark"), *dark_decl]
	automatic_decl = _declarations(keys, dark)
	parts = [
		_block(shape["light"], light_decl),
		_block(shape["dark"], dark_decl),
		f"@media {AUTOMATIC_MEDIA} {{\n" + _block(shape["automatic"], automatic_decl, "\t") + "}\n",
	]
	if color_scheme:
		parts.append(_block(shape["automatic"], [("color-scheme", "light dark")]))
	return "\n".join(parts)


def dark_delta(keys: Sequence[str], light: Mapping[str, str], dark: Mapping[str, str]) -> list[str]:
	"""The keys whose dark value differs from the light value, in key order."""
	light_decl = dict(_declarations(keys, light))
	dark_decl = dict(_declarations(keys, dark))
	return [key for key in keys if light_decl[key] != dark_decl[key]]


def emit_map_family(keys: Sequence[str], light: Mapping[str, str], dark: Mapping[str, str]) -> str:
	"""The Frappe map: a shared block with every declaration, then dark and automatic blocks with the delta.

	Sound only while no value reads another custom property of the same map (checked by the build), because a
	`var()` is resolved on the element that declares it: re-declaring an identical value on the same element
	is a no-op, so omitting it from the dark blocks changes no computed value (see SHAPES["map"]).
	"""
	shape = SHAPES["map"]
	delta = dark_delta(keys, light, dark)
	dark_decl = _declarations(delta, dark)
	return "\n".join(
		[
			_block(shape["shared"], _declarations(keys, light)),
			_block(shape["dark"], dark_decl),
			f"@media {AUTOMATIC_MEDIA} {{\n" + _block(shape["automatic"], dark_decl, "\t") + "}\n",
		]
	)


def emit_light_family(
	family: str,
	keys: Sequence[str],
	light: Mapping[str, str],
	*,
	color_scheme: bool = False,
) -> str:
	"""Only the light block of `emit_family`, byte-identical to it (for bundles that never see Dark)."""
	declarations = _declarations(keys, light)
	if color_scheme:
		declarations = [("color-scheme", "light"), *declarations]
	return _block(SHAPES[family]["light"], declarations)


def emit_scale(
	comfortable: Sequence[tuple[str, str]],
	compact: Sequence[tuple[str, str]],
	coarse: Sequence[tuple[str, str]],
) -> str:
	"""Comfortable, compact and coarse-pointer blocks of the mode-independent scale tokens."""
	parts = [
		_block((SCALE_COMFORTABLE,), comfortable),
		_block((SCALE_COMPACT,), compact),
		f"@media {SCALE_COARSE_MEDIA} {{\n" + _block(SCALE_COARSE, coarse, "\t") + "}\n",
	]
	return "\n".join(parts)


def emit_literals(sections: Sequence[tuple[str, Sequence[tuple[str, str]]]]) -> str:
	"""Sass variables (`$name: value;`), grouped under a comment per section."""
	parts = []
	for title, items in sections:
		lines = [f"// {title}"]
		lines += [f"${name}: {value};" for name, value in items]
		parts.append("\n".join(lines) + "\n")
	return "\n".join(parts)


def wrap_rtl_ignore(body: str) -> str:
	"""Wrap a bundle body in the rtlcss ignore pair (the stylesheets use no physical properties)."""
	return f"{RTL_BEGIN}\n{body.rstrip()}\n{RTL_END}\n"
