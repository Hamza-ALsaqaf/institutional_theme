import { chromium, BENCH, login, OUT } from "./lib.mjs";
import { HELPERS } from "./measure.mjs";
import { writeFileSync } from "node:fs";
const [which, user, lang] = process.argv.slice(2);
const base = BENCH[which];
const b = await chromium.launch({ args: ["--no-sandbox"] });
const ctx = await b.newContext({ locale: lang==="ar"?"ar":"en-US", viewport: { width: 1366, height: 768 }, reducedMotion: "reduce", forcedColors: "active" });
const page = await ctx.newPage();
await login(page, base, user, "Rev4-pass-9X!q");
await page.goto(base + "/desk/todo"); await page.waitForTimeout(3500); await page.evaluate(HELPERS);
const res = {};
const S = (sel)=> page.evaluate((sel)=>{ const e=document.querySelector(sel); if(!e) return null; const cs=getComputedStyle(e); const bf=getComputedStyle(e,'::before'); return { color:cs.color, bg:cs.backgroundColor, border:cs.borderTopStyle+' '+cs.borderTopWidth+' '+cs.borderTopColor, outline:cs.outlineStyle+' '+cs.outlineWidth+' '+cs.outlineColor, shadow:cs.boxShadow, fca:cs.forcedColorAdjust, before:{content:bf.content, bg:bf.backgroundColor, bgi:bf.backgroundImage.slice(0,50), bs:bf.borderTopStyle+' '+bf.borderTopWidth+' '+bf.borderTopColor, w:bf.width, h:bf.height} }; }, sel);
res.primary = await S(".primary-action");
res.subtle = await S(".menu-more-button");
res.badgeRed = await S(".es-badge[data-theme=red]");
res.badgeGreen = await S(".es-badge[data-theme=green]");
res.badgeAmber = await S(".es-badge[data-theme=amber]");
res.badgeGray = await S(".es-badge[data-filter='status,=,Cancelled']");
res.sbActive = await S(".body-sidebar .standard-sidebar-item.active-sidebar");
res.sbPlain = await S(".body-sidebar .standard-sidebar-item:not(.active-sidebar)");
res.dockActive = await S(".dock .dock-item.active");
res.dockPlain = await S(".dock .dock-item:not(.active)");
res.pillActive = await S(".es-pill[data-state=active]");
res.pillInactive = await S(".es-pill[data-state=inactive]");
res.input = await S(".frappe-control input, .standard-filter-section input");
await page.screenshot({ path: OUT + `forced-${which}-${lang}-list.png` });
// toast + menu in forced colours
await page.evaluate(()=>frappe.show_alert({message:'Forced colours toast', indicator:'red'}, 60)); await page.waitForTimeout(600);
res.toast = await S(".es-toast");
await page.screenshot({ path: OUT + `forced-${which}-${lang}-toast.png`, clip:{x:900,y:660,width:466,height:108} });
await page.evaluate(()=>document.querySelectorAll('.es-toast').forEach(e=>e.remove()));
await page.getByRole('button', {name: /^(Menu|القائمة|الخيارات)/}).first().click().catch(()=>{}); await page.waitForTimeout(600);
await page.keyboard.press("ArrowDown"); await page.waitForTimeout(200);
res.menuPanel = await S(".es-menu");
res.menuHl = await S(".es-menu [data-highlighted]");
await page.screenshot({ path: OUT + `forced-${which}-${lang}-menu.png` });
writeFileSync(`<out>/t6-${which}-${lang}.json`, JSON.stringify(res,null,1));
await b.close();
